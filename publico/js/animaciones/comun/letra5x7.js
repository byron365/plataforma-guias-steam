// Devuelve 35 puntos (fila por fila) o null si la letra no está
export function puntosLetra(c) {
  const dibujo = L[c];
  if (!dibujo) return null;
  return Uint8Array.from(dibujo.replace(/\|/g, ''), (x) => (x === '#' ? 1 : 0));
}
